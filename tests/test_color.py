class CieDe2000Test(unittest.TestCase):
    def test_sharma_table(self) -> None:
        for l1, a1, b1, l2, a2, b2, expected in SHARMA:
            with self.subTest(pair=(l1, a1, b1, l2, a2, b2)):
                self.assertAlmostEqual(delta_e2000((l1, a1, b1), (l2, a2, b2)), expected, places=4)
                self.assertAlmostEqual(delta_e2000((l2, a2, b2), (l1, a1, b1)), expected, places=4)

    def test_lab_of_white_and_black(self) -> None:
        white = (95.047, 100.0, 108.883)
        self.assertEqual(tuple(round(v, 6) for v in xyz_to_lab(white, white)), (100.0, 0.0, 0.0))
        self.assertEqual(tuple(round(v, 6) for v in xyz_to_lab((0, 0, 0), white)), (0.0, 0.0, 0.0))


